export function buildAgentTopicCards({
  activeGoal,
  activeTaskCount,
  assetDomainFileCount,
  assetDomainRiskCount,
  conversationCount,
  currentTask,
  doneTaskCount,
  failedTaskCount,
  goalCount,
  goalStatusLabel,
  memoryCount,
  modelEnabled,
  modelStatus,
  profileKnownCount,
  profileMissingCount,
  provider,
  providerName,
  snapshot,
  taskNextActionLabel,
  topic,
  topicId,
  visibleTaskCount,
  validationChecks,
  passedChecks,
  projectPhase,
  domains,
}) {
  const domain = (id) => domains?.[id];
  const topicRelatedCount = Array.isArray(topic?.relatedFiles) ? topic.relatedFiles.length : 0;
  const currentGoalTitle = activeGoal?.shortTitle || activeGoal?.title || "未选择";
  const taskResultCount = doneTaskCount + failedTaskCount;
  const cardsByTopic = {
    "project-identity": [["项目阶段", projectPhase], ["事实完整度", `${profileKnownCount}/5`], ["来源文件", `${topicRelatedCount || 2}`]],
    "project-progress": [["当前目标", currentGoalTitle], ["任务数量", `${visibleTaskCount}`], ["运行中", `${activeTaskCount}`]],
    "project-runbook": [["启动入口", "desktop/package.json"], ["检查命令", `${validationChecks.length || 3}`], ["状态", "可验证"]],
    "project-risks": [["风险来源", "HANDOFF / LESSONS"], ["失败任务", `${failedTaskCount}`], ["需关注", `${assetDomainRiskCount(domain("governance"))}`]],
    "local-project-state": [["接入状态", snapshot?.workspaceFacts?.status || "connected"], ["运行记录", `${snapshot?.runCount || 0}`], ["本地项目", snapshot?.currentProjectId ? "已选中" : "待选择"]],
    "current-goal": [["当前目标", currentGoalTitle], ["目标状态", activeGoal ? goalStatusLabel(activeGoal.status) : "空"], ["目标总数", `${goalCount}`]],
    "acceptance-criteria": [["验收状态", snapshot?.goalValidationReport?.status || "missing"], ["检查项", validationChecks.length ? `${passedChecks}/${validationChecks.length}` : "待补齐"], ["来源", ".omnidesk/data/goal-validation.json"]],
    "goal-history": [["已完成", `${domains?.doneGoals || 0}`], ["进行中", `${domains?.openGoals || 0}`], ["历史来源", ".omnidesk/data/goals.json"]],
    "collaboration-boundary": [["规则来源", "AGENTS.md"], ["状态", "已接入"]],
    "execution-permissions": [["自动边界", "受控命令"], ["确认边界", "写入/发布/高风险"], ["状态", "规则已接入"]],
    "documentation-rules": [["文档边界", "DOCUMENTATION"], ["命名规则", "NAMING"], ["状态", "已接入"]],
    "system-architecture": [["架构来源", "docs/ARCHITECTURE.md"], ["实现入口", "desktop/src"], ["状态", "待细化"]],
    "data-contracts": [["契约来源", "schemas / docs/data"], ["Schema 状态", assetDomainFileCount(domain("schema")) ? "已发现" : "待补齐"], ["用途", "状态和报告结构"]],
    "ui-standards": [["规范来源", "DESIGN_STANDARDS"], ["Token 来源", "desktop/src/styles.css"], ["状态", "已接入"]],
    "code-structure": [["结构来源", "CODE_STRUCTURE"], ["前端入口", "desktop/src/main.jsx"], ["后端入口", "desktop/src-tauri/src/main.rs"]],
    "validation-checks": [["检查项", `${validationChecks.length || 3}`], ["通过项", validationChecks.length ? `${passedChecks}` : "待运行"], ["状态", snapshot?.goalValidationReport?.status || "待生成"]],
    "validation-report": [["报告状态", snapshot?.goalValidationReport?.status || "missing"], ["检查结果", validationChecks.length ? `${passedChecks}/${validationChecks.length}` : "待运行"], ["用途", "验收和修复入口"]],
    "run-records": [["运行记录", `${snapshot?.runCount || 0}`], ["任务结果", `${taskResultCount}`], ["来源", ".omnidesk/evidence/runs/*"]],
    "handoff-records": [["交接来源", "HANDOFF.md"], ["任务结果", `${taskResultCount}`], ["状态", "可继续"]],
    "decision-records": [["决策来源", "DECISIONS / CHANGELOG"], ["状态", "待沉淀"], ["用途", "重要取舍记录"]],
    "lessons-learned": [["经验来源", "LESSONS.md"], ["记忆条目", `${memoryCount}`], ["用途", "踩坑约束"]],
    "task-list": [["任务总数", `${visibleTaskCount}`], ["当前查看", currentTask?.title || "选择一项任务"], ["下一步", currentTask ? taskNextActionLabel : "从看板选择任务"]],
    "execution-terminal": [["运行记录", `${snapshot?.runCount || 0}`], ["可用入口", "终端 tab / 受控检查 / 白名单命令"], ["边界", "不直接执行任意高风险命令"]],
    "execution-results": [["已完成任务", `${doneTaskCount}`], ["失败任务", `${failedTaskCount}`], ["最近结果", domains?.latestResult || "暂无执行结果"]],
    "model-connections": [["当前连接", providerName], ["启用状态", modelEnabled], ["当前模型", provider?.model || "未选择"], ["模型状态", modelStatus]],
    "tool-allowlist": [["受控检查", "Desktop 回归 / Web 构建 / Cargo 检查"], ["确认边界", "Patch 写入与检查分别审批"], ["执行方式", "Runtime 固定白名单"]],
    "security-boundary": [["写入边界", "工程文件写入必须经确认"], ["命令边界", "页面不传任意 shell"], ["密钥边界", "API Key 只保存在本地环境"]],
    "engineering-files": [["关键文件", `${assetDomainFileCount(domain("engineering")) || "待扫描"}`], ["风险文件", `${assetDomainRiskCount(domain("engineering"))}`], ["用途", "源码入口、配置和工程目录"]],
    "governance-files": [["治理文件", `${assetDomainFileCount(domain("governance")) || "待扫描"}`], ["需关注", `${assetDomainRiskCount(domain("governance"))}`], ["用途", "规则、状态、交接和运行说明"]],
    "report-artifacts": [["验收状态", snapshot?.goalValidationReport?.status || "待生成"], ["运行记录", `${snapshot?.runCount || 0}`], ["用途", "写入、检查与验收证据"]],
    "schema-assets": [["Schema 文件", `${assetDomainFileCount(domain("schema")) || "待扫描"}`], ["需关注", `${assetDomainRiskCount(domain("schema"))}`], ["用途", "约束 Agent 输入输出契约"]],
    "project-facts": [["事实完整度", `${profileKnownCount}/5`], ["事实来源", "profile / state / workspace-facts"], ["缺失项", profileMissingCount ? `${profileMissingCount}` : "无"]],
    "user-preferences": [["偏好状态", snapshot?.projectProfile?.userPreferences ? "已记录" : "待确认"], ["作用范围", "项目偏好 / 全局偏好"], ["来源", "对话提取 / 用户确认"]],
    "long-term-memory": [["记忆条目", `${memoryCount}`], ["沉淀方式", "事实 / 决策 / 经验"], ["状态", memoryCount ? "已接入" : "待沉淀"]],
    "conversation-summary": [["会话数量", `${conversationCount || "本地缓存"}`], ["沉淀方向", "任务 / 事实 / 偏好"], ["状态", "待产品化"]],
  };
  return cardsByTopic[topicId] || null;
}
